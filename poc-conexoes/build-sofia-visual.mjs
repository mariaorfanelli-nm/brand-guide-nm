// Build both previews from the same UI markup, styles and interactions.
// Run: node poc-conexoes/build-sofia-visual.mjs
import {readFileSync,writeFileSync} from 'node:fs';
import {renderSofiaVisual,visualModules} from './sofia-visual.mjs';
const root=new URL('./',import.meta.url);
const read=path=>readFileSync(new URL(path,root),'utf8');
const write=(path,value)=>writeFileSync(new URL(path,root),value);
let html=read('sofia.html');
const section=/<div class="sv-experience" data-sv-root>[\s\S]*?(?=<section class="sofia-evidence")/;
if(!section.test(html))throw Error('SofIA visual section boundary not found');
html=html.replace(section,renderSofiaVisual('contato.html?produto=sofia&amp;origem=sofia#formulario')+'\n');
write('sofia.html',html);
const css=read('sofia-visual.css'),logic=read('sofia-visual.mjs');
write('framer/SofiaVisualExperience.tsx',`// Generated by build-sofia-visual.mjs. Edit sofia-visual.mjs or sofia-visual.css.\nimport * as React from "react"\n${logic}\nconst visualCSS=${JSON.stringify(css)}\n/**\n * @framerSupportedLayoutWidth any\n * @framerSupportedLayoutHeight auto\n */\nexport default function SofiaVisualExperience({style}:{style?:React.CSSProperties}){\nconst ref=React.useRef<HTMLDivElement>(null);\nReact.useEffect(()=>enhanceSofiaVisual(ref.current?.querySelector('[data-sv-root]')),[]);\nreturn <div ref={ref} style={{width:'100%',...style}}><style>{visualCSS}</style><div dangerouslySetInnerHTML={{__html:renderSofiaVisual()}} /></div>\n}\n`);
const data=JSON.parse(read('content/sofia-platform.json'));
data.journeyTitle='Menos trabalho repetitivo. Mais inteligência jurídica.';
data.journeyDescription='Da primeira consulta à visão estratégica da carteira.';
data.visualExperience.modules=visualModules;
data.healthOperators.title='Da ouvidoria à NIP. Sem perder o fio do caso.';
data.healthOperators.description='Documentos, análise e resposta em uma jornada conectada.';
write('content/sofia-platform.json',JSON.stringify(data,null,2)+'\n');
console.log('Updated SofIA HTML, Framer component and visual content manifest.');
